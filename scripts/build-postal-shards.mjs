// Builds public/geo/postal/{FSA}.json from GeoNames' Canadian postal codes, Ontario only.
// The TRREB feed has no coordinates, so listings are placed at their postal code's centre.
//
// Data: GeoNames (CC BY 4.0), https://download.geonames.org/export/zip/CA_full.csv.zip
// Usage: node scripts/build-postal-shards.mjs /path/to/CA_full.txt
import { readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const input = process.argv[2];
if (!input) {
  console.error("Usage: node scripts/build-postal-shards.mjs /path/to/CA_full.txt");
  process.exit(1);
}

const outDir = new URL("../public/geo/postal/", import.meta.url).pathname;
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

// { "M5V": { "2T6": [43.6426, -79.3871], ... } }; 4 decimals is about 10 m
const shards = new Map();
for (const line of readFileSync(input, "utf8").split("\n")) {
  const [, code, , , province, , , , , lat, lng] = line.split("\t");
  if (province !== "ON" || !code || !lat || !lng) continue;
  const [fsa, ldu] = code.trim().toUpperCase().split(/\s+/);
  if (!fsa || !ldu) continue;
  if (!shards.has(fsa)) shards.set(fsa, {});
  shards.get(fsa)[ldu] = [Number(Number(lat).toFixed(4)), Number(Number(lng).toFixed(4))];
}

let codes = 0;
for (const [fsa, entries] of shards) {
  writeFileSync(join(outDir, `${fsa}.json`), JSON.stringify(entries));
  codes += Object.keys(entries).length;
}
writeFileSync(
  join(outDir, "README.md"),
  "Generated by scripts/build-postal-shards.mjs from GeoNames postal codes (CC BY 4.0, https://www.geonames.org).\n"
);
console.log(`${codes} Ontario postal codes in ${shards.size} files`);
