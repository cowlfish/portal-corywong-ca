// Checks the portal's source against the mechanical parts of RECO's advertising
// bulletins 5.1–5.6. Errors exit non-zero; warnings are phrases a person must review.
// It cannot judge whether a claim is true or whether consent exists — see docs/RECO-COMPLIANCE.md.
// Adapted from realestate.corywong.ca, which checks built HTML. The portal renders pages per
// request from the database, so this reads source instead: copy in .tsx/.ts files, and which
// layout each page renders under.
// Runs as part of `npm run build`; on its own: npm run check:reco

import { readdir, readFile } from 'node:fs/promises';
import { dirname, join, relative } from 'node:path';

// Must match the names registered with RECO exactly (Bulletin 5.1), and src/lib/reco.ts.
const BROKERAGE = 'Trustwell Realty Inc., Brokerage';
const AGENT = 'Cory Wong, Broker';
// Set to true only while a CREA member in good standing (Bulletin 5.2).
const REALTOR_MEMBER = false;

// Pages only Cory can open (agent role). Still checked for copy, but not advertising to the public.
const PRIVATE_PREFIXES = ['agent/'];

const ERRORS = [
  [/personal real estate corporation|\bP\.?R\.?E\.?C\.?\b/i, 'PRECs must not advertise (5.2)'],
  [/\b(approved|authori[sz]ed|endorsed|reviewed) by RECO\b|\bRECO[- ](approved|authori[sz]ed|endorsed)\b/i, 'must not imply RECO approval (5.5)'],
  [/Cory Wong Real Estate/, `unregistered business name; use "${AGENT}" and "${BROKERAGE}" (5.1, 5.2)`],
  ...(REALTOR_MEMBER ? [] : [[/REALTOR(?!\.ca)/i, 'REALTOR® is limited to CREA members in good standing (5.2)']]),
];

const WARNINGS = [
  [/\blicen[cs]ed\b/i, 'Ontario agents are "registered" with RECO, not licensed'],
  [/cost(s)? you nothing|no (direct )?cost to you|at no (direct )?cost/i, 'promise/offer: state its conditions (5.1)'],
  [/(?<!not )\bguarantee[ds]?\b/i, 'promise/offer: state its conditions (5.1)'],
  [/#\s?1\b|number one|\btop (agent|producer|\d+%?)/i, 'comparative/volume claim: give its basis (5.1)'],
  [/\bawards?\b|\bwinner\b/i, 'honour/award: give source, date, team size (5.1)'],
  [/\bsold (for|over|above|in)\b|\bjust sold\b/i, 'sold property: written consent needed (5.4)'],
  [/\btestimonials?\b|\bclient reviews?\b/i, 'testimonials: written consent from each person (5.3)'],
  [/\binstant(ly)?\b/i, 'accuracy: alerts are generated by a scheduled job, not instantly (5.1)'],
];

const root = new URL('../', import.meta.url).pathname;
const src = join(root, 'src');
const app = join(src, 'app');

async function sourceFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map(e => {
    const path = join(dir, e.name);
    if (e.isDirectory()) return e.name === 'generated' ? [] : sourceFiles(path);
    return /\.(tsx?|mjs)$/.test(e.name) && !e.name.endsWith('.d.ts') ? [path] : [];
  }));
  return nested.flat();
}

// Text roughly as rendered: tags dropped (not spaced, so "<b>Cory Wong</b>, Broker" still matches),
// comments and imports removed, entities and whitespace normalised.
function copyText(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\/|^\s*\/\/.*$/gm, ' ')
    .replace(/^import .*$/gm, ' ')
    .replace(/<\/?[A-Za-z][^<>]*?>/g, '')
    .replace(/\{["'`]\s*["'`]\}/g, ' ')
    .replace(/&amp;/g, '&').replace(/&nbsp;/g, ' ').replace(/&apos;|&#39;|&rsquo;/g, "'")
    .replace(/&reg;/g, '®').replace(/&mdash;/g, '—')
    .replace(/\s+/g, ' ');
}

// CREA's required trademark legend names REALTOR® without claiming membership.
function withoutCreaLegend(text) {
  return text.replace(/REALTOR®, REALTORS®,? and the REALTOR® logo are trademarks of [^.]*?members of CREA\./g, ' ');
}

function snippet(text, index) {
  return text.slice(Math.max(0, index - 50), index + 70).trim();
}

let errors = 0;
let warnings = 0;
const report = (level, where, message) => {
  console.log(`${level === 'error' ? 'ERROR' : 'warn '}  ${where}  ${message}`);
  level === 'error' ? errors++ : warnings++;
};

const files = (await sourceFiles(src)).sort();
const sources = new Map(await Promise.all(files.map(async f => [f, await readFile(f, 'utf8')])));

// The checker's names must be the ones the app renders.
const recoTs = sources.get(join(src, 'lib/reco.ts')) ?? '';
if (!recoTs.includes(`"${BROKERAGE}"`) || !recoTs.includes(`"${AGENT}"`)) {
  report('error', 'src/lib/reco.ts', 'BROKERAGE/AGENT differ from scripts/check-reco.mjs');
}

// The shared footer carries the full identification and RECO statement.
const footer = copyText(sources.get(join(src, 'components/ComplianceFooter.tsx')) ?? '');
for (const required of [BROKERAGE, AGENT, 'registered with the Real Estate Council of Ontario']) {
  if (!footer.includes(required)) report('error', 'src/components/ComplianceFooter.tsx', `missing "${required}" (5.1, 5.3)`);
}

// Copy checks, everywhere.
for (const [file, source] of sources) {
  if (file.endsWith('check-reco.mjs')) continue;
  const where = relative(root, file);
  const text = withoutCreaLegend(copyText(source));
  for (const [pattern, why] of ERRORS) {
    const m = text.match(pattern);
    if (m) report('error', where, `${why}: "…${snippet(text, m.index)}…"`);
  }
  for (const [pattern, why] of WARNINGS) {
    const m = text.match(pattern);
    if (m) report('warn', where, `${why}: "…${snippet(text, m.index)}…"`);
  }
}

// Identity checks: every page names the brokerage, through a layout with ComplianceFooter
// or on the page itself (Bulletins 5.1, 5.3). HTML built in route handlers too (e.g. CMA export).
// <title> text doesn't count: it isn't shown on the page.
const identifies = s => {
  const body = s.replace(/^\s*title:.*$/gm, '');
  return body.includes('ComplianceFooter') || body.includes(BROKERAGE) || body.includes('BrandMark');
};
let pages = 0;
for (const [file, source] of sources) {
  const isPage = file.startsWith(app) && /\/page\.tsx$/.test(file);
  const isHtmlRoute = file.startsWith(app) && /\/route\.ts$/.test(file) && /text\/html/.test(source);
  if (!isPage && !isHtmlRoute) continue;
  pages++;
  const route = relative(app, file);
  if (identifies(source)) continue;

  let covered = false;
  for (let dir = dirname(file); dir.startsWith(app); dir = dirname(dir)) {
    if (identifies(sources.get(join(dir, 'layout.tsx')) ?? '')) { covered = true; break; }
  }
  if (covered) continue;
  const level = PRIVATE_PREFIXES.some(p => route.startsWith(p)) ? 'warn' : 'error';
  report(level, relative(root, file), `no brokerage identification on page or in its layouts (5.1, 5.3)`);
}

// External links (5.3): each must read as leaving the site, not as part of Cory's services.
const externalHosts = new Set();
for (const source of sources.values()) {
  for (const m of source.matchAll(/href=["{`]*["'`](https?:\/\/[^"'`]+)["'`]/g)) {
    const host = new URL(m[1]).host;
    if (host !== 'portal.corywong.ca') externalHosts.add(host);
  }
}

console.log(`\n${sources.size} source files, ${pages} pages checked: ${errors} error(s), ${warnings} warning(s).`);
console.log(`External sites linked (each must read as not part of Cory's services, 5.3): ${[...externalHosts].sort().join(', ') || 'none'}`);
process.exit(errors ? 1 : 0);
